#include <bits/stdc++.h>
using namespace std;

int main() {

    cout << "Hello, World!" << "\n";
    cout << "My C++ journey starts now!" << "\n";

    return 0;
}

/*
 OUTPUT:
 Hello, World!
 My C++ journey starts now!

 KEY TAKEAWAY:
 - #include <bits/stdc++.h> → includes all libraries
 - main() → where the program starts
 - cout << → prints output
 - "\n" → moves to next line (faster than endl)
 - return 0 → program ended successfully
*/
