#include <bits/stdc++.h>
using namespace std;

int main() {

    int a, b;
    cout << "Enter the value of A: ";
    cin >> a;
    cout << "Enter the value of B: ";
    cin >> b;
    cout << "The sum of A and B: " << a + b << "\n";

    return 0;
}

